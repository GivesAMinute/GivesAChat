/* ---------------------------------------------------------
   Odysee custom emote manifest  (the "48 px" set)

   GENERATED by evaluating Odysee's own emote module rather than
   transcribed by hand, so these paths are exact:

     const url  = (p) => `https://static.odycdn.com/emoticons/${p}`;
     const E    = (name, path) => ({ name: `:${name}:`, url: url(path) });
     const set  = (dir, suffix) => [ E("sleep", `${dir}/Sleep${suffix}.png`), ... ];
     const emotes = set("48%20px", "%402x");

   The client builds four size variants — 24 px, 36px, 48 px and
   72 px, with suffixes "", "@1.5x", "@2x" and "@3x" — but only
   the 48/@2x set is exported for chat. That is why every custom
   emote is a @2x file.

   THE TOKEN IS NOT THE FILENAME. There is no rule connecting
   them; the mapping is arbitrary and had to come from the
   source:

     :sleep:       Sleep@2x.png       capitalised
     :rock:        ROCK@2x.png        upper-cased
     :cry_1:       cry@2x.png         suffix means "first cry"
     :cry_2:       cry 2@2x.png       ...not a size variant
     :confused_2:  confused@2x.png    but _2 here means the base
     :confused_1:  confused@2x-1.png  and _1 means the "-1" file
     :what:        what_@2x.png       trailing underscore
     :woodoo_doll: woodo doll@2x.png  misspelt on their CDN
     :space_doge:  doge@2x.png        prefix dropped entirely

   Spaces are percent-encoded. One entry in their source uses a
   literal space where the others use %20 — normalised here,
   since a browser encodes it either way.

   80 emotes. A token not in this list falls through to
   OdyseeRoom's twemoji probing, so a newly added emote degrades
   to guess-and-check rather than to nothing.
--------------------------------------------------------- */

