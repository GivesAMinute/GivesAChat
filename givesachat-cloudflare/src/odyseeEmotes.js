/**
 * @param {string} name  a :token: with the colons stripped
 * @returns {{kind:"emote", url:string}|null}
 */
export function odyseeCustomEmote(name) {
  const path = CUSTOM[name];
  return path ? { kind: "emote", url: CDN + path } : null;
}

